-- 2. CREATE CATEGORIES TABLE
CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    description TEXT,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

-- 3. CREATE SUBCATEGORIES TABLE
CREATE TABLE IF NOT EXISTS public.subcategories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT REFERENCES public.categories(id) ON DELETE CASCADE NOT NULL,
    name TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    description TEXT,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

-- 4. CREATE INDEXES ON SLUGS (for high-performance lookups)
CREATE INDEX IF NOT EXISTS categories_slug_idx ON public.categories (slug);
CREATE INDEX IF NOT EXISTS subcategories_slug_idx ON public.subcategories (slug);

-- 5. ENABLE ROW LEVEL SECURITY (RLS) - Supabase Security Best Practice
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.subcategories ENABLE ROW LEVEL SECURITY;

-- 6. CREATE RLS POLICIES
-- Drop existing policies first to ensure the script is fully idempotent
DROP POLICY IF EXISTS "Allow public read access to categories" ON public.categories;
DROP POLICY IF EXISTS "Allow public read access to subcategories" ON public.subcategories;
DROP POLICY IF EXISTS "Allow admin write access to categories" ON public.categories;
DROP POLICY IF EXISTS "Allow admin write access to subcategories" ON public.subcategories;

-- Public Read-Only Access
CREATE POLICY "Allow public read access to categories" 
ON public.categories FOR SELECT 
USING (true);

CREATE POLICY "Allow public read access to subcategories" 
ON public.subcategories FOR SELECT 
USING (true);

-- Authenticated Admin Full Access
CREATE POLICY "Allow admin write access to categories" 
ON public.categories FOR ALL 
TO authenticated 
USING (auth.jwt() -> 'app_metadata' ->> 'role' = 'admin')
WITH CHECK (auth.jwt() -> 'app_metadata' ->> 'role' = 'admin');

CREATE POLICY "Allow admin write access to subcategories" 
ON public.subcategories FOR ALL 
TO authenticated 
USING (auth.jwt() -> 'app_metadata' ->> 'role' = 'admin')
WITH CHECK (auth.jwt() -> 'app_metadata' ->> 'role' = 'admin');

